def make_pdf(path: Path, pages: list, header: str, footer: str) -> None:
    c = canvas.Canvas(str(path), pagesize=A4)
    height = A4[1]
    for n, lines in enumerate(pages, start=1):
        c.setFont("Body", 8)
        c.drawString(50, height - 30, header)
        c.drawString(50, 25, footer.format(n=n, total=len(pages)))
        y = height - 70
        for kind, text in lines:
            if kind == "title":
                c.setFont("Bold", 13)
                y -= 6
            elif kind == "head":
                c.setFont("Bold", 11)
                y -= 10
            else:
                c.setFont("Body", 10)
            c.drawString(50, y, text)
            y -= 16
        c.showPage()
    c.save()


