def inn12(base10: str) -> str:
    w11 = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
    w12 = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
    d11 = sum(int(c) * w for c, w in zip(base10, w11)) % 11 % 10
    d12 = sum(int(c) * w for c, w in zip(base10 + str(d11), w12)) % 11 % 10
    return base10 + str(d11) + str(d12)


